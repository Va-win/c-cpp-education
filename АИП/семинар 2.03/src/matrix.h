#pragma once

// Емкость матрицы. Занятая часть rows x cols хранится отдельно.
const int ROWS = 4;
const int COLS = 5;

// Сумма строки i: элементы a[i][0] … a[i][cols - 1].
int row_sum(const int a[][COLS], int cols, int i);

// Сумма столбца j: элементы a[0][j] … a[rows - 1][j].
int col_sum(const int a[][COLS], int rows, int j);

// Находит максимум занятой части. Если максимумов несколько, берет первый:
// строки просматриваются сверху вниз, каждая слева направо.
// Удаляет строку и столбец максимума сдвигом. Столбцов после этого cols - 1.
// Возвращает новое число строк rows - 1. При rows < 1 или cols < 1 возвращает -1, a не меняется.
int remove_max_row_col(int a[][COLS], int rows, int cols);

// Пишет занятые клетки в out по спирали, рамка за рамкой: верхняя строка слева направо,
// правый столбец сверху вниз, нижняя строка справа налево, левый столбец снизу вверх.
// Возвращает число записанных клеток, rows * cols. При rows < 1 или cols < 1 возвращает 0.
// В out должно помещаться rows * cols чисел. Ячейки out дальше не меняются.
int write_spiral(const int a[][COLS], int rows, int cols, int out[]);

// Обнуляет в занятой части каждую строку и каждый столбец, где до вызова стоял 0.
// Нули, которые поставила сама функция, не учитываются.
// Если нулей в занятой части нет, возвращает false и a не меняет.
bool clear_zero_rows_cols(int a[][COLS], int rows, int cols);
